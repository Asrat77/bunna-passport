#!/usr/bin/env node
/**
 * Writes src/ui/icons.ts: the Phosphor icons the Mini App uses (DESIGN.md
 * §2.4), as path strings on Phosphor's 256-unit grid, so only these end up in
 * the bundle and map pins can draw them with Path2D. To add an icon, put its
 * Phosphor name in ICONS (fill weight as "<name>-fill") and rerun.
 *
 * Usage: node scripts/icons.mjs
 */
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const ICONS = [
  "arrow-clockwise",
  "arrow-right",
  "camera",
  "caret-down",
  "caret-left",
  "caret-right",
  "chart-bar",
  "check",
  "coffee",
  "coffee-bean",
  "coffee-fill",
  "compass",
  "crosshair",
  "dots-three-vertical",
  "download-simple",
  "eye",
  "eye-slash",
  "fire",
  "magnifying-glass",
  "map-pin",
  "map-trifold",
  "pencil-simple",
  "plus",
  "plus-circle",
  "share-network",
  "shuffle",
  "stamp",
  "user-plus",
  "warning",
];

const require = createRequire(import.meta.url);
const camel = (name) => "ph" + name.replace(/(^|-)(\w)/g, (_, __, c) => c.toUpperCase());

const lines = ICONS.map((name) => {
  const weight = name.endsWith("-fill") ? "fill" : "regular";
  const svg = readFileSync(require.resolve(`@phosphor-icons/core/${weight}/${name}.svg`), "utf8");
  const paths = [...svg.matchAll(/<path d="([^"]+)"/g)].map((match) => match[1]);
  if (paths.length !== 1) throw new Error(`${name}: expected one path, found ${paths.length}`);
  return `export const ${camel(name)} = "${paths[0]}";`;
});

const out = join(dirname(fileURLToPath(import.meta.url)), "../src/ui/icons.ts");
writeFileSync(
  out,
  `// Generated by scripts/icons.mjs from @phosphor-icons/core (MIT). Do not edit.\n\n${lines.join("\n")}\n`,
);
console.log(`Wrote ${ICONS.length} icons to ${out}`);
